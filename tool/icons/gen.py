#!/usr/bin/env python3
"""Subsets Lucide (ISC) to the icons in names.txt and writes lib/app/icons.dart.

Usage: python3 tool/icons/gen.py <lucide.ttf> <codepoints.json>
(both ship in the lucide-static npm package or lucide_icons_flutter's assets).
Needs fonttools (pip install fonttools).
"""
import json, pathlib, re, subprocess, sys

root = pathlib.Path(__file__).resolve().parents[2]
ttf, cps = sys.argv[1], json.load(open(sys.argv[2]))
names = [l.strip() for l in (root / 'tool/icons/names.txt').read_text().splitlines() if l.strip() and not l.startswith('#')]
missing = [n for n in names if n not in cps]
if missing:
    sys.exit(f'Not in Lucide: {missing}')
subprocess.run(['pyftsubset', ttf, '--unicodes=' + ','.join(f'U+{cps[n]:04X}' for n in names),
                f'--output-file={root / "assets/fonts/Lucide.ttf"}', '--no-hinting', '--desubroutinize'], check=True)

def camel(n):
    p = re.split(r'[-_]', n)
    s = p[0] + ''.join(x[:1].upper() + x[1:] for x in p[1:])
    return s if not s[0].isdigit() else 'i' + s

rtl = {'chevron-right', 'chevron-left', 'arrow-left', 'log-out', 'log-in', 'external-link'}
lines = ['// GENERATED by tool/icons/gen.py from tool/icons/names.txt — do not edit.', '// Lucide icons (ISC licence, https://lucide.dev), same set as the web admin.',
         "import 'package:flutter/widgets.dart';", '', 'abstract final class AppIcons {']
for n in names:
    m = ', matchTextDirection: true' if n in rtl else ''
    lines.append(f"  static const IconData {camel(n)} = IconData(0x{cps[n]:x}, fontFamily: 'Lucide'{m});")
lines.append('}')
(root / 'lib/app/icons.dart').write_text('\n'.join(lines) + '\n')
print(f'{len(names)} icons')
